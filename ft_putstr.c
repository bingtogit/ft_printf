#include "ft_printf.h"

int ft_putstr(char *s)
{
    int i;
    int j;
    
    if (!s)
        s = "(null)";
    i = 0;
    j = 0;
    while(s[i])
    {
        j = write(1, &s[i], 1);
        if (j == -1)
            return (-1);
        i++;
    }
    return (i);
}
